-- B3 — تصنيف المراجعة التقليدي: سبق / سبقي / منزل. «سبق» هو قسم الحفظ
-- الجديد القائم أصلاً على ward_logs (hifz_from/hifz_to) بلا أي تغيير؛
-- هذا الترحيل يضيف تصنيف «سبقي/منزل» لمقاطع المراجعة فقط.
--
-- إضافي بحت وقابل للتشغيل المتكرر: ADD COLUMN IF NOT EXISTS فقط، لا
-- حذف ولا تعديل لأي عمود أو صف قائم. بلا قيمة افتراضية — العمود
-- NULL لكل الصفوف الحالية فتبقى الأوراد القديمة صحيحة تماماً كما كانت،
-- والعدّادات تعامل NULL كـ«بلا تصنيف».
--
-- على جدول ward_review_segments (لا ward_logs) عمداً: الورد الواحد قد
-- يجمع مراجعة سبقية وأخرى منزلية بيوم واحد، فالتصنيف صفة المقطع لا
-- الورد. CHECK يمنع أي قيمة خارج المسمّيين ويسمح بـNULL للمقاطع غير
-- المصنَّفة (التصنيف اختياري دائماً). لا فهرس جديد: كل الاستعلامات
-- تصل للمقاطع عبر ward_log_id المفهرس أصلاً، ولا تصفية بالمسار وحده.

ALTER TABLE ward_review_segments
  ADD COLUMN IF NOT EXISTS track TEXT
  CHECK (track IN ('sabqi', 'manzil') OR track IS NULL);
