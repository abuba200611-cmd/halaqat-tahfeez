/**
 * مفتاح عدّاد الدخول الفاشل لكل (IP + معرّف): يمنع تخمين حساب واحد من
 * عنوان واحد، دون أن يقفل غريبٌ حسابَ الضحية لصاحبه من عنوان آخر. يبقى
 * حدّ الـIP المستقل فوقه لكبح المسح عبر معرّفات كثيرة. الدخول الناجح لا
 * يمسّ أي عدّاد (لا احتساب ولا مسح) فلا يستهلك حصة أحد.
 */
export function loginFailureKey(scope: string, ip: string, identifier: string): string {
  return `${scope}:${ip}:${identifier.slice(0, 200)}`;
}
